#!/usr/bin/env python3
"""References for the binary32 decoders (tests/f32_decoder_validation.rs).

Each pattern's value by mpmath (ldexp of the integer fields, 200 digits) and
trunc(v * 2^F) toward zero at F = 0, 10, 16, 20, 30, 64, cross-checked with
Python integers. Patterns: signed zeros, subnormals (smallest, largest,
random), normals across every exponent, the edges of the Q22.10 / Q12.20 /
Q16.16 ranges, the largest finite value, infinities and NaNs. No floats.
"""
import os
from mpmath import mp, mpf, ldexp

mp.dps = 200


class Rng:
    def __init__(self, s):
        self.s = s

    def next(self):
        s = self.s
        s ^= s >> 12
        s ^= (s << 25) & ((1 << 64) - 1)
        s ^= s >> 27
        self.s = s
        return (s * 0x2545F4914F6CDD1D) & ((1 << 64) - 1)


def value(bits):
    s, e, m = bits >> 31, (bits >> 23) & 255, bits & ((1 << 23) - 1)
    if e == 255:
        return None
    v = ldexp(mpf(m), -149) if e == 0 else ldexp(mpf((1 << 23) + m), e - 150)
    return -v if s else v


def trunc_int(bits, f):
    """The same by integers only."""
    s, e, m = bits >> 31, (bits >> 23) & 255, bits & ((1 << 23) - 1)
    if e != 0:
        m |= 1 << 23
    k = (-149 if e == 0 else e - 150) + f
    mag = m << k if k >= 0 else m >> -k
    return -mag if s else mag


def main():
    rng = Rng(0xF32B175)
    pats = [0x00000000, 0x80000000, 0x00000001, 0x80000001, 0x007FFFFF, 0x00800000, 0x3F800000, 0xBFC00000,
            0x7F7FFFFF, 0xFF7FFFFF, 0x7F800000, 0xFF800000, 0x7FC00000, 0xFFFFFFFF, 0x7F800001,
            0x4A000000, 0xCA000000, 0x49FFFFFF, 0xC9FFFFFF,  # +-2^21 and just below: the Q22.10 edge
            0x45000000, 0xC5000000, 0x44FFFFFF,  # +-2^11: the Q12.20 edge
            0x47000000, 0x46FFFFFF, 0x3A800000, 0x3A7FFFFF, 0x35800000, 0x357FFFFF]  # 2^15, 2^-10, 2^-20
    for e in range(0, 255, 3):
        pats.append(((rng.next() & 1) << 31) | (e << 23) | (rng.next() & 0x7FFFFF))
    for _ in range(40):
        pats.append(rng.next() & 0xFFFFFFFF)
    rows = []
    for p in pats:
        v = value(p)
        per = []
        for f in (0, 10, 16, 20, 30, 64):
            if v is None:
                per.append("Err(OverflowDetected::InvalidInput)")
                continue
            t = int(ldexp(v, f))  # mpmath int() truncates toward zero
            assert t == trunc_int(p, f), (hex(p), f)
            per.append(f"Ok({t})" if -(1 << 127) < t < (1 << 127) else "Err(OverflowDetected::TierOverflow)")
        rows.append((p, per))
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "data", "f32_refs.rs")
    with open(out, "w") as fh:
        fh.write("// Generated by scripts/generate_f32_refs.py (mpmath at 200 digits, integer cross-check). Do not edit.\n\n")
        fh.write("use g_math::fixed_point::imperative::OverflowDetected;\n\n")
        fh.write("/// (pattern, trunc(v * 2^F) at F = 0, 10, 16, 20, 30, 64)\n")
        fh.write("pub const CASES: &[(u32, [Result<i128, OverflowDetected>; 6])] = &[\n")
        for p, per in rows:
            fh.write(f"    ({p:#010x}, [{', '.join(per)}]),\n")
        fh.write("];\n")
    print(f"{len(rows)} patterns; wrote {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
