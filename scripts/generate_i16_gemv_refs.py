#!/usr/bin/env python3
"""References for I16Matrix (tests/i16_gemv_validation.rs): exact row sums
sum_j F[r][j] * t[j], by Python integers and again by mpmath (fsum at 60
digits, exact for these magnitudes); the generator asserts they agree.

Cases cover every regime of the kernel's 32-bit lanes: small entries (one
flush per row), entries near 2^15 (a flush every step), -32768 in both the
matrix and the vector (the exact scalar path), including one 16-bit pair
whose two products sum to 2^31, column tails (not a multiple
of 16), zero vectors. No floats.
"""
import os
from mpmath import mp, mpf, fsum

mp.dps = 60


class Rng:
    def __init__(self, s):
        self.s = s

    def next(self):
        s = self.s
        s ^= s >> 12
        s ^= (s << 25) & ((1 << 64) - 1)
        s ^= s >> 27
        self.s = s
        return (s * 0x2545F4914F6CDD1D) & ((1 << 64) - 1)


def main():
    rng = Rng(0x16C0FFEE)
    rnd = lambda lim: (rng.next() % (2 * lim + 1)) - lim
    cases = []
    # (rows, cols, matrix limit, vector limit, plant -32768 in matrix, in vector)
    for rows, cols, fl, tl, pf, pt in [
        (6, 256, 1 << 10, 1 << 12, False, False),
        (5, 256, 32767, 32767, False, False),
        (4, 256, 32767, 32767, True, True),
        (4, 256, 32767, 32767, True, False),
        (3, 273, 1 << 14, (1 << 15) - 1, False, False),
        (3, 9, 32767, 32767, True, True),
        (2, 64, 32767, 0, False, False),
        (3, 48, 32767, 32767, True, True),
    ]:
        f = [rnd(fl) for _ in range(rows * cols)]
        t = [rnd(tl) for _ in range(cols)]
        if pf:
            f[rng.next() % len(f)] = -32768
            f[0] = -32768
        if pt:
            t[0] = -32768
            t[rng.next() % cols] = -32768
        if rows == 3 and cols == 48:
            # one 16-bit pair of (-32768) * (-32768) twice: 2^31, past a 32-bit lane
            for j in (16, 17):
                f[cols + j] = -32768
                t[j] = -32768
        sums = []
        for r in range(rows):
            s = sum(f[r * cols + j] * t[j] for j in range(cols))
            assert int(fsum(mpf(f[r * cols + j]) * t[j] for j in range(cols))) == s
            sums.append(s)
        cases.append((rows, cols, f, t, sums))
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "data", "i16_gemv_refs.rs")
    with open(out, "w") as fh:
        fh.write("// Generated by scripts/generate_i16_gemv_refs.py (integers, confirmed by mpmath). Do not edit.\n\n")
        fh.write("pub const CASES: &[(usize, usize, &[i16], &[i16], &[i64])] = &[\n")
        for rows, cols, f, t, sums in cases:
            fh.write(f"    ({rows}, {cols}, &[{', '.join(map(str, f))}], &[{', '.join(map(str, t))}], &[{', '.join(map(str, sums))}]),\n")
        fh.write("];\n")
    print(f"{len(cases)} cases; wrote {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
