#!/usr/bin/env python3
"""References for the batched and row-subset RowScaledTQ19 forms
(tests/rowscaled_batch_validation.rs), by mpmath with an integer cross-check.

The released rounding rules, at the activations' format F:
  Default  matvec : dot = trunc(acc / 3^9), out = floor(dot * s / 2^32)
  Default  q2f    : w = trunc(acc * 2^F / 3^9), out = floor(w * s / 2^32)
  Nearest (both)  : floor(acc * s * 2^extra / (3^9 * 2^32) + 1/2)
with acc = sum raw_i * x_i exact and s the row's Q32.32 scale. Every value is
computed by mpmath at 80 digits (the quotients are real numbers there, then
truncated or floored) and by Python integers; the generator asserts they
agree. Matrices have a column tail (not a multiple of 8), batches of nine
activations (past the kernel's eight). No floats.
"""
import os
from mpmath import mp, mpf, floor as mfloor

mp.dps = 80


class Rng:
    def __init__(self, s):
        self.s = s

    def next(self):
        s = self.s
        s ^= s >> 12
        s ^= (s << 25) & ((1 << 64) - 1)
        s ^= s >> 27
        self.s = s
        return (s * 0x2545F4914F6CDD1D) & ((1 << 64) - 1)


def trunc_div(a, b):
    q = abs(a) // abs(b)
    return q if (a >= 0) == (b > 0) else -q


def mtrunc(v):
    return int(mfloor(v)) if v >= 0 else -int(mfloor(-v))


def main():
    rng = Rng(0x5CA1ED19)
    cases = []
    for rows, cols, frac, bits in ((12, 37, 10, 21), (5, 2304, 10, 20), (7, 203, 16, 22)):
        data = [(rng.next() % 59049) - 29524 for _ in range(rows * cols)]
        scales = [(1 << 28) + rng.next() % (1 << 33) for _ in range(rows)]
        acts = [[(rng.next() % (1 << bits)) - (1 << (bits - 1)) for _ in range(cols)] for _ in range(9)]
        outs = []
        for x in acts:
            per = []
            for r in range(rows):
                acc = sum(data[r * cols + c] * x[c] for c in range(cols))
                s = scales[r]
                # integers
                dot = trunc_div(acc, 19683)
                d_mv = (dot * s) >> 32
                w = trunc_div(acc << frac, 19683)
                d_q = (w * s) >> 32
                n_mv = (2 * acc * s + (19683 << 32)) // (2 * (19683 << 32))
                n_q = (2 * (acc * s << frac) + (19683 << 32)) // (2 * (19683 << 32))
                # mpmath
                ma = mpf(acc)
                m_dot = mtrunc(ma / 19683)
                assert m_dot == dot
                assert int(mfloor(mpf(m_dot) * s / mpf(2) ** 32)) == d_mv
                m_w = mtrunc(ma * mpf(2) ** frac / 19683)
                assert m_w == w
                assert int(mfloor(mpf(m_w) * s / mpf(2) ** 32)) == d_q
                assert int(mfloor(ma * s / (mpf(19683) * mpf(2) ** 32) + mpf(1) / 2)) == n_mv
                assert int(mfloor(ma * s * mpf(2) ** frac / (mpf(19683) * mpf(2) ** 32) + mpf(1) / 2)) == n_q
                assert all(-(1 << 31) <= v < (1 << 31) for v in (d_mv, n_mv)) and all(-(1 << 63) <= v < (1 << 63) for v in (d_q, n_q))
                per.append((d_mv, d_q, n_mv, n_q))
            outs.append(per)
        cases.append((rows, cols, frac, data, scales, acts, outs))

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "data", "rowscaled_batch_refs.rs")
    with open(out, "w") as f:
        f.write("// Generated by scripts/generate_rowscaled_batch_refs.py (mpmath at 80 digits, integer cross-check). Do not edit.\n\n")
        f.write("pub struct Case {\n    pub rows: usize,\n    pub cols: usize,\n    pub frac: u32,\n    pub data: &'static [i16],\n")
        f.write("    pub scales: &'static [u64],\n    pub acts: &'static [&'static [i32]],\n")
        f.write("    /// per activation, per row: (Default matvec, Default q2f, Nearest matvec, Nearest q2f)\n")
        f.write("    pub outs: &'static [&'static [(i32, i64, i32, i64)]],\n}\n\npub const CASES: &[Case] = &[\n")
        for rows, cols, frac, data, scales, acts, outs in cases:
            f.write(f"    Case {{\n        rows: {rows},\n        cols: {cols},\n        frac: {frac},\n")
            f.write("        data: &[" + ", ".join(map(str, data)) + "],\n")
            f.write("        scales: &[" + ", ".join(map(str, scales)) + "],\n        acts: &[\n")
            for x in acts:
                f.write("            &[" + ", ".join(map(str, x)) + "],\n")
            f.write("        ],\n        outs: &[\n")
            for per in outs:
                f.write("            &[" + ", ".join(f"({a}, {b}, {c}, {d})" for a, b, c, d in per) + "],\n")
            f.write("        ],\n    },\n")
        f.write("];\n")
    print(f"{len(cases)} cases, {sum(c[0] * 9 for c in cases)} rows x 4 values; wrote {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
